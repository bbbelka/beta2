create or replace function public.update_shop_order_status(
  p_order_id bigint,
  p_status text,
  p_tracking_number text default '',
  p_status_note text default ''
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_current_status text;
  v_product_ids bigint[];
  v_ledger_count integer;
  v_product_count integer;
  v_updated_count integer;
  v_returned_count integer;
begin
  if auth.uid() is null or not public.is_admin() then
    raise exception 'Управлять заказами могут только администраторы';
  end if;
  if p_order_id is null or p_status is null or p_status not in (
    'ordered', 'sent', 'at_warehouse', 'ready_for_pickup', 'delivered', 'cancelled'
  ) then
    raise exception 'Некорректный статус заказа';
  end if;

  select status
  into v_current_status
  from public.orders
  where id = p_order_id
  for update;
  if not found then
    raise exception 'Заказ не найден';
  end if;

  if v_current_status = 'cancelled' and p_status <> 'cancelled' then
    raise exception 'Отменённый заказ нельзя возобновить через смену статуса';
  end if;
  if p_status = 'cancelled' and v_current_status <> 'cancelled' then
    if v_current_status <> 'ordered' then
      raise exception 'Автоматическая отмена доступна только до отправки заказа';
    end if;

    select count(*)::integer, array_agg(product_id order by product_id)
    into v_ledger_count, v_product_ids
    from public.shop_order_inventory
    where order_id = p_order_id and returned_at is null;
    if v_ledger_count = 0 then
      raise exception 'Заказ создан до учёта остатков. Проверьте возврат товара и скорректируйте остаток вручную';
    end if;

    perform product.id
    from public.products as product
    where product.id = any(v_product_ids)
    order by product.id
    for update;

    select count(*)::integer
    into v_product_count
    from public.shop_order_inventory as inventory
    join public.products as product on product.id = inventory.product_id
    where inventory.order_id = p_order_id and inventory.returned_at is null;
    if v_product_count <> v_ledger_count then
      raise exception 'Не все товары заказа доступны для безопасного возврата остатка';
    end if;

    perform set_config('app.stock_change_action', 'order_return', true);
    perform set_config('app.stock_change_reason', 'Возврат при отмене заказа', true);
    perform set_config('app.stock_change_order_id', p_order_id::text, true);
    update public.products as product
    set stock_quantity = product.stock_quantity + inventory.quantity,
        updated_at = now()
    from public.shop_order_inventory as inventory
    where inventory.order_id = p_order_id
      and inventory.returned_at is null
      and product.id = inventory.product_id;
    get diagnostics v_updated_count = row_count;
    if v_updated_count <> v_ledger_count then
      raise exception 'Не удалось восстановить остаток целиком; отмена заказа отменена';
    end if;
    update public.shop_order_inventory
    set returned_at = now()
    where order_id = p_order_id and returned_at is null;
    get diagnostics v_returned_count = row_count;
    if v_returned_count <> v_ledger_count then
      raise exception 'Не удалось зафиксировать возврат остатка целиком';
    end if;
  end if;

  update public.orders
  set status = p_status,
      tracking_number = coalesce(p_tracking_number, ''),
      status_note = coalesce(p_status_note, ''),
      updated_at = now()
  where id = p_order_id;
end;
