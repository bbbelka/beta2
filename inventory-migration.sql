create or replace function public.sync_product_availability_from_stock()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if new.stock_quantity is null then
    new.available := false;
    return new;
  end if;
  if new.stock_quantity < 0 then
    raise exception 'Остаток должен быть целым неотрицательным числом';
  end if;

  if tg_op = 'INSERT' then
    new.available := new.stock_quantity > 0;
    if new.stock_quantity > 0 then
      new.sold_at := null;
    end if;
  elsif new.stock_quantity is distinct from old.stock_quantity
      or new.available is distinct from old.available then
    new.available := new.stock_quantity > 0;
    if new.stock_quantity > 0 then
      new.sold_at := null;
    elsif old.stock_quantity > 0 then
      new.sold_at := coalesce(new.sold_at, now());
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists products_sync_availability_from_stock on public.products;
create trigger products_sync_availability_from_stock
before insert or update
on public.products
for each row execute function public.sync_product_availability_from_stock();

create or replace function public.capture_product_change_history()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_actor_type text;
  v_reason text;
  v_action text;
  v_order_id bigint;
  v_field text;
  v_old jsonb;
  v_new jsonb;
begin
  v_actor_type := case
    when auth.uid() is null then 'system'
    when public.is_admin() then 'admin'
    else 'customer'
  end;
  v_reason := nullif(current_setting('app.stock_change_reason', true), '');
  v_action := nullif(current_setting('app.stock_change_action', true), '');
  if v_action not in ('manual_stock_adjustment', 'order_deduction', 'order_return') then
    v_action := null;
  end if;
  if nullif(current_setting('app.stock_change_order_id', true), '') ~ '^[0-9]+$' then
    v_order_id := current_setting('app.stock_change_order_id', true)::bigint;
  end if;

  if tg_op = 'DELETE' then
    insert into public.product_change_history (
      product_id, product_name, action, field_name, previous_value, new_value,
      changed_by, actor_type, reason, order_id
    ) values (
      old.id, old.name, 'product_deleted', 'product',
      jsonb_build_object('name', old.name, 'price', old.price, 'stock_quantity', old.stock_quantity),
      null, auth.uid(), v_actor_type, v_reason, v_order_id
    );
    return old;
  end if;

  if tg_op = 'INSERT' then
    insert into public.product_change_history (
      product_id, product_name, action, field_name, previous_value, new_value,
      changed_by, actor_type, reason, order_id
    ) values (
      new.id, new.name, 'product_created', 'product', null,
      jsonb_build_object('name', new.name, 'price', new.price, 'stock_quantity', new.stock_quantity),
      auth.uid(), v_actor_type, v_reason, v_order_id
    );
    insert into public.product_change_history (
      product_id, product_name, action, field_name, previous_value, new_value,
      changed_by, actor_type, reason, order_id
    ) values (
      new.id, new.name, 'stock_initialization', 'stock_quantity', null,
      to_jsonb(new.stock_quantity), auth.uid(), v_actor_type, v_reason, v_order_id
    );
    return new;
  end if;

  if old.stock_quantity is distinct from new.stock_quantity then
    insert into public.product_change_history (
      product_id, product_name, action, field_name, previous_value, new_value,
      changed_by, actor_type, reason, order_id
    ) values (
      new.id, new.name, coalesce(v_action, 'manual_stock_adjustment'), 'stock_quantity',
      to_jsonb(old.stock_quantity), to_jsonb(new.stock_quantity),
      auth.uid(), v_actor_type, v_reason, v_order_id
    );
  end if;

  if old.available is distinct from new.available then
    insert into public.product_change_history (
      product_id, product_name, action, field_name, previous_value, new_value,
      changed_by, actor_type, reason, order_id
    ) values (
      new.id, new.name, 'availability_change', 'available',
      to_jsonb(old.available), to_jsonb(new.available),
      auth.uid(), v_actor_type, v_reason, v_order_id
    );
  end if;

  v_old := to_jsonb(old);
  v_new := to_jsonb(new);
  foreach v_field in array array['name', 'price', 'description', 'category', 'seller', 'year', 'link', 'image', 'photos']
  loop
    if v_old -> v_field is distinct from v_new -> v_field then
      v_action := case v_field
        when 'name' then 'name_change'
        when 'price' then 'price_change'
        when 'description' then 'description_change'
        else 'product_field_change'
      end;
      insert into public.product_change_history (
        product_id, product_name, action, field_name, previous_value, new_value,
        changed_by, actor_type, reason, order_id
      ) values (
        new.id, new.name, v_action, v_field, v_old -> v_field, v_new -> v_field,
        auth.uid(), v_actor_type, v_reason, v_order_id
      );
    end if;
  end loop;
  return new;
end;
$$;

drop trigger if exists products_capture_change_history on public.products;
create trigger products_capture_change_history
after insert or update or delete on public.products
for each row execute function public.capture_product_change_history();

create or replace function public.product_price_amount(p_price text)
returns numeric
language plpgsql
immutable
set search_path = public, pg_temp
as $$
declare
  v_price text;
  v_amount numeric;
begin
  if p_price is null then
    raise exception 'Цена товара не указана';
  end if;

  v_price := regexp_replace(
    replace(replace(btrim(p_price), chr(160), ' '), chr(8239), ' '),
    '[[:space:]]+',
    ' ',
    'g'
  );
  v_price := regexp_replace(v_price, '[[:space:]]*(₽|руб\.?)$', '', 'i');
  if v_price !~ '^([0-9]+|[0-9]{1,3}( [0-9]{3})+)([,.][0-9]{1,2})?$' then
    raise exception 'У товара указана некорректная цена';
  end if;

  v_price := replace(replace(v_price, ' ', ''), ',', '.');
  v_amount := v_price::numeric;
  if v_amount <= 0 then
    raise exception 'Цена товара должна быть больше нуля';
  end if;
  return v_amount;
end;
$$;
revoke all on function public.product_price_amount(text) from public, anon, authenticated;

create or replace function public.set_product_stock(
  p_product_id bigint,
  p_stock_quantity integer,
  p_reason text default null
)
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_stock integer;
begin
  if auth.uid() is null or not public.is_admin() then
    raise exception 'Изменять остатки могут только администраторы';
  end if;
  if p_product_id is null or (p_stock_quantity is not null and p_stock_quantity < 0) then
    raise exception 'Остаток должен быть неизвестным либо целым неотрицательным числом';
  end if;
  if char_length(coalesce(p_reason, '')) > 500 then
    raise exception 'Причина изменения должна содержать не более 500 символов';
  end if;

  perform set_config('app.stock_change_action', 'manual_stock_adjustment', true);
  perform set_config('app.stock_change_reason', coalesce(nullif(btrim(p_reason), ''), ''), true);
  perform set_config('app.stock_change_order_id', '', true);
  update public.products
  set stock_quantity = p_stock_quantity, updated_at = now()
  where id = p_product_id
  returning stock_quantity into v_stock;
  if not found then
    raise exception 'Товар не найден';
  end if;
  return v_stock;
end;
$$;
revoke all on function public.set_product_stock(bigint, integer, text) from public, anon, authenticated;
